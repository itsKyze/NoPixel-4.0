/**
 * NoPixel 4.0 Cleanup Pipeline
 * - Removes all .bak backup files
 * - Removes obsolete duplicate .js and .css bundles from nui/dist/assets
 * - Removes output bundle artifacts (index-*.js, index-*.css, Vite chunks) from web/src and web/public/assets
 */

const fs = require('fs');
const path = require('path');

const base = path.resolve(__dirname);

let deletedBak = 0;
let deletedSrc = 0;
let deletedPublic = 0;
let deletedDist = 0;

console.log('==================================================');
console.log('NoPixel 4.0 Workspace Cleanup Pipeline');
console.log('Removing .bak files, duplicate .js/.css & source artifacts');
console.log('==================================================');

// 1. Delete all .bak files globally
function cleanBak(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name !== 'node_modules' && e.name !== '.git') {
        cleanBak(full);
      }
    } else if (e.isFile() && e.name.endsWith('.bak')) {
      try {
        fs.unlinkSync(full);
        deletedBak++;
      } catch (err) {}
    }
  }
}

// 2. Clean web/src and web/public/assets
function cleanWebDir(webDir) {
  const srcDir = path.join(webDir, 'src');
  const publicAssetsDir = path.join(webDir, 'public', 'assets');

  // Collect all imported modules in source code (App.tsx, main.tsx, etc.)
  const importedFiles = new Set();
  if (fs.existsSync(srcDir)) {
    const files = fs.readdirSync(srcDir);
    for (const f of files) {
      if (f.endsWith('.tsx') || f.endsWith('.ts') || f.endsWith('.jsx')) {
        const content = fs.readFileSync(path.join(srcDir, f), 'utf8');
        const matches = [
          ...content.matchAll(/from\s+["']\.\/([^"']+)["']/g),
          ...content.matchAll(/import\s+["']\.\/([^"']+)["']/g)
        ];
        for (const m of matches) {
          importedFiles.add(m[1]);
        }
      }
    }

    // Clean web/src
    for (const f of files) {
      // Never allow index-* bundles or css bundles in src
      if (f.startsWith('index-') && (f.endsWith('.js') || f.endsWith('.css'))) {
        try {
          fs.unlinkSync(path.join(srcDir, f));
          deletedSrc++;
        } catch (e) {}
        continue;
      }

      // If it's a double-hashed chunk (e.g. config-xxx-yyy.js generated by Vite), delete it from src
      if (f.endsWith('.js') && f.includes('-') && f.split('-').length >= 3 && !f.startsWith('v-packages')) {
        try {
          fs.unlinkSync(path.join(srcDir, f));
          deletedSrc++;
        } catch (e) {}
        continue;
      }

      // If it's a .js file in src that is neither imported by source nor a component, delete if not imported
      if (f.endsWith('.js') && !importedFiles.has(f) && path.basename(path.dirname(webDir)) !== 'np-ui') {
        // Keep vendor libraries, delete leftover build chunks
        if (!f.startsWith('v-packages-') && !f.startsWith('vendor-') && !f.startsWith('vite-') && !f.startsWith('commonjsHelpers-')) {
          try {
            fs.unlinkSync(path.join(srcDir, f));
            deletedSrc++;
          } catch (e) {}
        }
      }
    }
  }

  // Clean web/public/assets
  if (fs.existsSync(publicAssetsDir)) {
    const pubFiles = fs.readdirSync(publicAssetsDir);
    for (const f of pubFiles) {
      // Remove any index-* bundles from public assets
      if (f.startsWith('index-') && (f.endsWith('.js') || f.endsWith('.css'))) {
        try {
          fs.unlinkSync(path.join(publicAssetsDir, f));
          deletedPublic++;
        } catch (e) {}
        continue;
      }

      // Remove double-hashed build chunks from public assets
      if (f.endsWith('.js') && f.includes('-') && f.split('-').length >= 3 && !f.startsWith('v-packages')) {
        try {
          fs.unlinkSync(path.join(publicAssetsDir, f));
          deletedPublic++;
        } catch (e) {}
      }
    }
  }
}

// 3. Clean obsolete duplicate index-*.js and index-*.css in nui/dist/assets
function cleanNuiDist(distDir) {
  const assetsDir = path.join(distDir, 'assets');
  const indexHtml = path.join(distDir, 'index.html');
  if (!fs.existsSync(assetsDir) || !fs.existsSync(indexHtml)) return;

  const html = fs.readFileSync(indexHtml, 'utf8');
  const activeFiles = new Set();
  
  const scriptMatches = [...html.matchAll(/src=["']\.\/assets\/([^"']+)["']/gi)];
  for (const m of scriptMatches) activeFiles.add(m[1]);
  const linkMatches = [...html.matchAll(/href=["']\.\/assets\/([^"']+)["']/gi)];
  for (const m of linkMatches) activeFiles.add(m[1]);

  const files = fs.readdirSync(assetsDir);
  for (const f of files) {
    // Check duplicate index files
    if (f.startsWith('index-') && (f.endsWith('.js') || f.endsWith('.css'))) {
      if (!activeFiles.has(f)) {
        try {
          fs.unlinkSync(path.join(assetsDir, f));
          deletedDist++;
        } catch (e) {}
      }
    }
  }
}

function scanResources(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === 'web') {
        cleanWebDir(full);
      }
      if (e.name === 'dist' && path.basename(dir) === 'nui') {
        cleanNuiDist(full);
      }
      if (e.name !== 'node_modules' && e.name !== '.git') {
        scanResources(full);
      }
    }
  }
}

cleanBak(base);
scanResources(base);

console.log('Cleanup Complete:');
console.log(`- Deleted .bak files: ${deletedBak}`);
console.log(`- Deleted output artifacts from web/src: ${deletedSrc}`);
console.log(`- Deleted output artifacts from web/public/assets: ${deletedPublic}`);
console.log(`- Deleted obsolete duplicate bundles from nui/dist/assets: ${deletedDist}`);
console.log(`Total items cleaned: ${deletedBak + deletedSrc + deletedPublic + deletedDist}`);
console.log('==================================================');
